# ティア: (名称, 基準確率, 生涯賞金[万円], 出走数, 維持費を払う月数)
TIERS = [
    ("未勝利", 0.62, 250, 4, 14),
    ("1勝", 0.24, 1500, 12, 24),
    ("2〜3勝", 0.09, 5000, 25, 34),
    ("OP〜重賞入着", 0.04, 15000, 35, 40),
    ("重賞勝ち〜G1", 0.01, 50000, 40, 48),
]
SHARE = 0.78        # 賞金のうち会員に回る割合(仮定)
TEATE = 50          # 特別出走手当/走[万円](減額あり、概算)
K = 0.04            # 能力スコアへの感応度
ALPHA = 0.35        # 価格が示す市場評価の織り込み度
WIN_CAP = 0.70      # 勝ち上がり確率の上限


def ability(h):
    return (h[2] * 40 + h[3] * 25 + h[5] * 20 + h[4] * 15) / 100 * 10


def evaluate(h):
    ab, price = ability(h), h[7]
    f = math.exp(K * (ab - 70)) * (price / 2500) ** ALPHA
    p = [t[1] * (f if i else 1) for i, t in enumerate(TIERS)]
    p[1] = min(p[1], 0.55)
    win = sum(p[1:])
    if win > WIN_CAP:
        p[1:] = [x * WIN_CAP / win for x in p[1:]]
    p[0] = 1 - sum(p[1:])
    rev = cost = 0.0
    for (_, _, prize, starts, months), pp in zip(TIERS, p):
        rev += pp * (prize * SHARE + starts * TEATE)
        ins = price * (0.032 + 0.0224 + (0.016 if months >= 34 else 0))
        cost += pp * (price + 60 * months + ins)
    return dict(ability=ab, win=sum(p[1:]), up=sum(p[2:]), ratio=rev / cost,
                per_unit=(rev - cost) / h[8] * 1e4)


